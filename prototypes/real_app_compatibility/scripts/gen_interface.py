"""Generates the host's dynamic interface (dynamic_interface.yaml) from the app's package config.

    python3 -I gen_interface.py <app/.dart_tool/package_config.json> <full|core> <out.yaml>

The interface lists, by exact declaring-library URI (the format has no wildcards), everything a
bytecode module may call, use as a type, extend/implement or override:
  full: dart:* libraries, every Flutter framework library under lib/src/<layer>/, the app's own
        packages, and selected third-party packages (collection, crypto, shared_preferences...).
  core: only dart:core and the host contracts (used to measure the size cost of 'full').
Part files are skipped: members belong to the library that declares the part.
"""
import json
import pathlib
import re
import sys
from urllib.parse import urlparse, unquote

DART_CALLABLE = ['dart:core', 'dart:async', 'dart:collection', 'dart:convert', 'dart:math',
                 'dart:typed_data', 'dart:io', 'dart:isolate', 'dart:ui', 'dart:ffi', 'dart:developer']
DART_EXTENDABLE = ['dart:core', 'dart:async', 'dart:collection', 'dart:convert', 'dart:typed_data']
FLUTTER_LAYERS = ['animation', 'foundation', 'gestures', 'painting', 'physics', 'rendering',
                  'scheduler', 'semantics', 'services', 'widgets']
APP_PACKAGES = ['app_models', 'app_core', 'shared_state', 'patchable_utils', 'product_service',
                'user_service', 'feature_catalog', 'feature_profile', 'compat_suites']
THIRD_PARTY = ['collection', 'crypto', 'typed_data', 'meta', 'vector_math', 'characters',
               'shared_preferences', 'shared_preferences_platform_interface', 'plugin_platform_interface']


def is_part(path: pathlib.Path) -> bool:
    for line in path.read_text(encoding='utf-8', errors='replace').splitlines():
        s = line.strip()
        if s.startswith('part of'):
            return True
        if s.startswith(('import ', 'export ', 'library', 'class ', 'void ', 'const ')):
            return False
    return False


_WEB_IMPORT = re.compile(r"^import\s+'(dart:(js_interop|js_interop_unsafe|ui_web|html|js_util|js)|[^']*\bweb\.dart)'", re.M)


def web_only(path: pathlib.Path) -> bool:
    """Web variants of conditional imports (never compiled for Android) must not be listed."""
    return path.name.endswith('_web.dart') or bool(_WEB_IMPORT.search(path.read_text(encoding='utf-8', errors='replace')))


def package_libs(name: str, root: pathlib.Path, sub: str = '') -> list[str]:
    lib = root / 'lib'
    base = lib / sub if sub else lib
    out = []
    for f in sorted(base.rglob('*.dart')):
        if not is_part(f) and not web_only(f):
            out.append(f'package:{name}/{f.relative_to(lib).as_posix()}')
    return out


def main() -> None:
    cfg_path, mode, out = pathlib.Path(sys.argv[1]), sys.argv[2], pathlib.Path(sys.argv[3])
    cfg = json.loads(cfg_path.read_text())
    roots = {}
    for p in cfg['packages']:
        uri = p['rootUri']
        path = pathlib.Path(unquote(urlparse(uri).path)) if uri.startswith('file:') else (cfg_path.parent / uri).resolve()
        roots[p['name']] = path

    libs, ext, dyn = [], [], []
    if mode == 'full':
        libs += DART_CALLABLE
        ext += DART_EXTENDABLE
        for layer in FLUTTER_LAYERS:
            fl = package_libs('flutter', roots['flutter'], f'src/{layer}')
            libs += fl
            ext += fl
        for name in APP_PACKAGES:
            pl = package_libs(name, roots[name])
            libs += pl
            ext += pl
        # Experiment: only app_models may be called dynamically (probe_dynamic checks both sides).
        dyn = package_libs('app_models', roots['app_models'])
        for name in THIRD_PARTY:
            if name in roots:
                libs += package_libs(name, roots[name])
    elif mode == 'core':
        libs = ['dart:core', *package_libs('app_core', roots['app_core'])]
        ext = list(libs)
    else:
        raise SystemExit(f'unknown mode {mode}')

    def section(items):
        return ''.join(f"  - library: '{u}'\n" for u in items)

    out.write_text(
        '# Generated by scripts/gen_interface.py - do not edit.\n'
        f'callable:\n{section(libs)}'
        f'can-be-used-as-type:\n{section(libs)}'
        f'extendable:\n{section(ext)}'
        f'can-be-overridden:\n{section(ext)}'
        + (f'dynamically-callable:\n{section(dyn)}' if dyn else ''))
    print(f'{out}: {len(libs)} callable libraries, {len(ext)} extendable/overridable ({mode})')


if __name__ == '__main__':
    main()
