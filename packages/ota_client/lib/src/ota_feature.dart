import 'package:flutter/widgets.dart';

/// The zero-boilerplate, host-owned contract type of a patchable feature (runtime contract,
/// section 3).
///
/// A patch carries **renamed copies** of your feature packages, so a feature's own class is a
/// different type inside a patch. The app therefore reaches every feature through a type that is
/// part of the store build and never copied: this class (from the SDK), or an abstract class in
/// one of your shared packages.
///
/// ```dart
/// // packages/products/lib/products.dart
/// class ProductsFeature extends OtaFeature {
///   @override
///   Widget build(BuildContext context, [Object? arguments]) => const ProductsScreen();
/// }
///
/// // in the app (generated by the flutter_ota CLI):
/// OtaFeature get products => FlutterOta.feature<OtaFeature>('products', () => ProductsFeature());
/// ```
abstract class OtaFeature {
  /// Const constructor, so subclasses can be const.
  const OtaFeature();

  /// Builds the feature's UI. [arguments] are optional, feature-defined values.
  Widget build(BuildContext context, [Object? arguments]);
}
