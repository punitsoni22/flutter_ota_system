import 'dart:convert';

import 'package:crypto/crypto.dart';

/// `dart:` libraries a patch may use. Internal and unsafe libraries (`dart:_internal`, `dart:ffi`,
/// `dart:mirrors`, `dart:_vm`, ...) are never listed.
const interfaceDartLibraries = [
  'dart:async',
  'dart:collection',
  'dart:convert',
  'dart:core',
  'dart:developer',
  'dart:io',
  'dart:isolate',
  'dart:math',
  'dart:typed_data',
  'dart:ui',
];

/// The module loader package: never callable from a patch (a patch must not load modules).
const _loaderPrefix = 'package:dynamic_modules/';

/// Version of the interface policy. Bump it when [buildDynamicInterface] changes its output for
/// the same input, so a release records which rule produced its interface.
const interfacePolicyVersion = 2;

/// The generated dynamic interface of a store build.
class DynamicInterface {
  DynamicInterface(this.yaml, this.libraries);

  /// File content (UTF-8, `\n` line ends).
  final String yaml;

  /// Sorted library URIs listed in every section.
  final List<String> libraries;

  List<int> get bytes => utf8.encode(yaml);
  String get sha256Hex => sha256.convert(bytes).toString();
}

/// Builds `dynamic_interface.yaml` from the libraries of the store build's kernel (`link.dill`).
///
/// Policy 2 (deterministic: same kernel libraries -> byte-identical file):
///
/// - every `package:` library that the store build compiled (Flutter, the app's own packages,
///   path packages and third-party packages), because a patch can only use libraries that are
///   already in the store build;
/// - the `dart:` libraries in [interfaceDartLibraries] that the kernel contains;
/// - the same list in all four sections (callable, can-be-used-as-type, extendable,
///   can-be-overridden), so a patch may call, extend and override everything the app could;
/// - never `package:dynamic_modules` (the module loader) or the generated entry point (passed in
///   [exclude]);
/// - no `dynamically-callable` section (the patch guard rejects dynamic calls anyway).
///
/// Libraries that are not in the kernel (for example web-only conditional imports) cannot be
/// listed: the compiler refuses unknown libraries.
DynamicInterface buildDynamicInterface(Iterable<String> kernelLibraries, {Set<String> exclude = const {}}) {
  final present = kernelLibraries.toSet()..removeAll(exclude);
  final libs = <String>{
    for (final d in interfaceDartLibraries)
      if (present.contains(d)) d,
    for (final u in present)
      if (u.startsWith('package:') && !u.startsWith(_loaderPrefix) && !u.contains("'") && !u.contains('\n')) u,
  }.toList()..sort();
  if (!libs.contains('dart:core')) throw const FormatException('the kernel has no dart:core');
  final body = StringBuffer(
    '# Generated by flutter_ota (interface policy $interfacePolicyVersion). Do not edit.\n'
    '# Lists the libraries of the store build that a patch may use.\n',
  );
  for (final section in ['callable', 'can-be-used-as-type', 'extendable', 'can-be-overridden']) {
    body.writeln('$section:');
    for (final l in libs) {
      body.writeln("  - library: '$l'");
    }
  }
  return DynamicInterface(body.toString(), libs);
}
