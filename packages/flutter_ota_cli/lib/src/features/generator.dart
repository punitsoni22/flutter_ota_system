import 'dart:io';

import 'package:path/path.dart' as p;

import '../errors.dart';
import '../release/ota_entry.dart' show mainDeclaresArgs, otaMainFileName, renderOtaMain;
import 'discovery.dart';
import 'package_graph.dart';

/// Result of [generateFeatureRegistry].
class RegistryResult {
  RegistryResult(this.path, this.content, this.changed, this.graph, {this.entryPath, this.entryChanged = false});

  /// Absolute path of `lib/flutter_ota_features.g.dart`.
  final String path;
  final String content;

  /// Whether the file on disk was created or changed (in check mode: whether it is NOT up to
  /// date).
  final bool changed;
  final FeatureGraph graph;

  /// Absolute path of `lib/flutter_ota_main.g.dart` when the app has one (the release command
  /// creates it; see [syncOtaEntry]), else null.
  final String? entryPath;

  /// Whether that entry file was rewritten (in check mode: whether it is NOT up to date).
  final bool entryChanged;
}

/// Keeps an existing `lib/flutter_ota_main.g.dart` identical to what the release command writes.
///
/// The release command owns this file: it creates it with [renderOtaMain] (the single renderer,
/// docs/architecture/phase-4-sdk-runtime.md §3). The features generator never creates it and has
/// no template of its own; it only re-renders an existing file with that same renderer, so
/// `features generate` and `release` always produce identical bytes. Returns the file's path (or
/// null when there is none) and whether it differs from the expected content (with [check], the
/// file is not written).
(String?, bool) syncOtaEntry(String appLibDir, {bool check = false}) {
  final entry = File(p.join(appLibDir, otaMainFileName));
  final main = File(p.join(appLibDir, 'main.dart'));
  if (!entry.existsSync() || !main.existsSync()) return (null, false);
  final expected = renderOtaMain(mainTakesArgs: mainDeclaresArgs(main.readAsStringSync()));
  final differs = entry.readAsStringSync() != expected;
  if (differs && !check) entry.writeAsStringSync(expected);
  return (entry.path, differs);
}

/// Renders the registry for [graph] (deterministic: same graph, same bytes).
///
/// Each feature gets one typed getter. Its type is the feature's HOST-OWNED contract type (the
/// SDK's `OtaFeature` or an abstract class of a shared package), never the feature's own class:
/// a patch contains renamed copies of feature packages, so only host-owned types match.
///
/// Feature libraries are imported as `feature_<package>` and contract libraries of shared
/// packages as `contract_<package>`, never with the plain package name: a getter named like the
/// prefix would hide it inside the class body.
String renderRegistry(FeatureGraph graph) {
  final features = graph.features.values.toList()..sort((a, b) => a.package.compareTo(b.package));
  final contractLibs = <String>{
    for (final f in features)
      if (f.contract != null && f.contractLibraryUri != sdkLibraryUri) f.contractLibraryUri,
  }.toList()..sort();
  final contractPrefix = <String, String>{};
  final used = <String>{};
  for (final lib in contractLibs) {
    final pkg = Uri.parse(lib).pathSegments.first;
    var prefix = 'contract_$pkg';
    for (var n = 2; used.contains(prefix); n++) {
      prefix = 'contract_${pkg}_$n';
    }
    used.add(prefix);
    contractPrefix[lib] = prefix;
  }
  String contractRef(FeatureEntry f) => f.contractLibraryUri == sdkLibraryUri
      ? f.contractType
      : '${contractPrefix[f.contractLibraryUri]}.${f.contractType}';

  final b = StringBuffer()
    ..writeln('// generated by flutter_ota (4F) in the app: lib/$registryFileName')
    ..writeln('// Do not edit by hand. Regenerate with: flutter_ota features generate')
    ..writeln("import '$sdkLibraryUri';");
  for (final lib in contractLibs) {
    b.writeln("import '$lib' as ${contractPrefix[lib]};");
  }
  for (final f in features) {
    b.writeln("import '${f.libraryUri}' as feature_${f.package};");
  }
  b.writeln('abstract final class OtaFeatures {');
  for (var i = 0; i < features.length; i++) {
    final f = features[i];
    if (i > 0) b.writeln();
    b
      ..writeln('  static ${contractRef(f)} get ${f.getter} =>')
      ..writeln(
        "      FlutterOta.feature<${contractRef(f)}>('${f.slot}', () => feature_${f.package}.${f.className}());",
      );
  }
  b.writeln('}');
  return b.toString();
}

/// Discovers the features of the app in [projectDir] and writes `lib/flutter_ota_features.g.dart`
/// (a pure registry: it registers no module loader; the release command generates
/// `lib/flutter_ota_main.g.dart` for that). An existing `lib/flutter_ota_main.g.dart` is kept
/// identical to the release command's output (see [syncOtaEntry]).
///
/// The release command (4D) calls this before every store build, so the registry always matches
/// the package graph of the build. With [check] nothing is written; [RegistryResult.changed] then
/// says whether the file is NOT up to date.
///
/// Throws [CliException] when the graph has problems (for example a feature without a host-owned
/// contract type). When the app has no features and no registry exists yet, nothing is written.
RegistryResult generateFeatureRegistry(String projectDir, {bool check = false}) {
  final graph = FeatureGraph.build(ProjectPackages.load(projectDir));
  if (graph.problems.isNotEmpty) {
    throw CliException('Cannot generate the feature registry:\n${graph.problems.map((x) => '  - $x').join('\n')}');
  }
  final path = p.join(graph.project.app.libDir, registryFileName);
  final content = renderRegistry(graph);
  final (entryPath, entryChanged) = syncOtaEntry(graph.project.app.libDir, check: check);
  final f = File(path);
  final current = f.existsSync() ? f.readAsStringSync() : null;
  if (graph.features.isEmpty && current == null) {
    return RegistryResult(path, content, false, graph, entryPath: entryPath, entryChanged: entryChanged);
  }
  final differs = current != content;
  if (!check && differs) {
    f.parent.createSync(recursive: true);
    f.writeAsStringSync(content);
  }
  return RegistryResult(path, content, differs, graph, entryPath: entryPath, entryChanged: entryChanged);
}
