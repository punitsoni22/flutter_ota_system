import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

import '../errors.dart';
import '../owner/bundle_builder.dart' show dynamicModulesPackageFiles;
import '../toolchain/manager.dart';
import 'app_project.dart';

/// The only package name the pinned Dart lets import `dart:_internal` (the VM's module loader).
const loaderPackageName = 'dynamic_modules';

/// Generated store-build entry point inside the app's `lib/` (SDK runtime doc §3).
const otaMainFileName = 'flutter_ota_main.g.dart';

/// Where the CLI keeps the app's copy of `dynamic_modules` (relative to the project).
const loaderPackageRelDir = '$otaWorkDirName/packages/$loaderPackageName';

/// Developer/owner escape hatch: a `dynamic_modules` package folder to use when the toolchain
/// overlay does not ship one yet (overlays built before milestone 4D).
const loaderPackageDirEnv = 'FLUTTER_OTA_DYNAMIC_MODULES_DIR';

/// `lib/flutter_ota_main.g.dart`, exactly as specified in docs/architecture/phase-4-sdk-runtime.md
/// §3. When the app's `main` takes `List<String> args`, they are passed through.
String renderOtaMain({required bool mainTakesArgs}) {
  final sig = mainTakesArgs ? 'void main(List<String> args) {' : 'void main() {';
  final call = mainTakesArgs ? 'app.main(args);' : 'app.main();';
  return '''
// GENERATED by flutter_ota. Do not edit.
import 'dart:typed_data';

import 'package:dynamic_modules/dynamic_modules.dart' as dm;
import 'package:flutter_ota_system/flutter_ota_system.dart';

import 'main.dart' as app;

/// Found by name in the verifier process: keep the pragma.
@pragma('vm:entry-point')
Future<Object?> flutterOtaLoadModule(Uint8List bytes) => dm.loadModuleFromBytes(bytes);

$sig
  FlutterOta.registerModuleLoader(flutterOtaLoadModule);
  $call
}
''';
}

/// Whether `main` in [mainDartSource] declares a parameter (simple text check; comments ignored).
bool mainDeclaresArgs(String mainDartSource) {
  final noComments = mainDartSource
      .replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '')
      .replaceAll(RegExp(r'//[^\n]*'), '');
  final m = RegExp(
    r'(?:^|[\s;}])(?:void|Future<void>|FutureOr<void>|dynamic)?\s*main\s*\(([^)]*)\)',
    multiLine: true,
  ).firstMatch(noComments);
  return m != null && m.group(1)!.trim().isNotEmpty;
}

/// Writes `lib/flutter_ota_main.g.dart` (only when its content changes). Returns its path.
String writeOtaMain(String projectDir) {
  final main = File(p.join(projectDir, 'lib', 'main.dart'));
  final content = renderOtaMain(mainTakesArgs: mainDeclaresArgs(main.readAsStringSync()));
  final out = File(p.join(projectDir, 'lib', otaMainFileName));
  if (!out.existsSync() || out.readAsStringSync() != content) out.writeAsStringSync(content);
  return out.path;
}

/// Finds the `dynamic_modules` package to use: the toolchain's own copy
/// (`<toolchain>/packages/dynamic_modules`, covered by the verified install record), else the
/// `FLUTTER_OTA_DYNAMIC_MODULES_DIR` escape hatch.
String locateLoaderPackage(ResolvedToolchain tc, Map<String, String> env) {
  final inToolchain = tc.dynamicModulesPackage;
  if (dynamicModulesPackageFiles.every((f) => File(p.join(inToolchain, f)).existsSync())) return inToolchain;
  final override = env[loaderPackageDirEnv];
  if (override != null && override.isNotEmpty) {
    if (!dynamicModulesPackageFiles.every((f) => File(p.join(override, f)).existsSync())) {
      throw CliException('$loaderPackageDirEnv=$override is not a $loaderPackageName package.');
    }
    return p.normalize(p.absolute(override));
  }
  throw CliException(
    'The toolchain ${tc.id} does not ship the $loaderPackageName package (overlays from before '
    'milestone 4D). Install a newer toolchain, or (toolchain builders only) set '
    '$loaderPackageDirEnv to a copy of it.',
  );
}

/// Copies the loader package into `.flutter_ota/packages/dynamic_modules` (only its known files,
/// so nothing else can ride along) and returns the SHA-256 of `lib/dynamic_modules.dart`.
String installLoaderPackage(String projectDir, String source) {
  final dest = p.join(projectDir, loaderPackageRelDir);
  final name = (loadYaml(File(p.join(source, 'pubspec.yaml')).readAsStringSync()) as YamlMap)['name'];
  if (name != loaderPackageName) throw CliException('$source is not the $loaderPackageName package.');
  for (final rel in dynamicModulesPackageFiles) {
    final from = File(p.join(source, rel));
    final to = File(p.join(dest, rel))..parent.createSync(recursive: true);
    final bytes = from.readAsBytesSync();
    if (!to.existsSync() || sha256.convert(to.readAsBytesSync()) != sha256.convert(bytes)) to.writeAsBytesSync(bytes);
  }
  return sha256.convert(File(p.join(dest, 'lib', 'dynamic_modules.dart')).readAsBytesSync()).toString();
}

/// Makes sure `pubspec.yaml` depends on `dynamic_modules` (path `.flutter_ota/packages/...`).
/// Returns true when the file was changed. A dependency the developer already declared is kept
/// only if it points at that same folder.
bool ensureLoaderDependency(String projectDir) {
  final f = File(p.join(projectDir, 'pubspec.yaml'));
  final text = f.readAsStringSync();
  final y = loadYaml(text) as YamlMap;
  final deps = y['dependencies'];
  if (deps is YamlMap && deps.containsKey(loaderPackageName)) {
    final d = deps[loaderPackageName];
    if (d is YamlMap && d['path'] is String && p.equals(p.normalize(d['path'] as String), loaderPackageRelDir)) {
      return false;
    }
    throw CliException(
      'pubspec.yaml already declares $loaderPackageName differently. It must be:\n'
      '  $loaderPackageName:\n    path: $loaderPackageRelDir',
    );
  }
  final lines = text.split('\n');
  final i = lines.indexWhere((l) => RegExp(r'^dependencies:\s*(#.*)?$').hasMatch(l));
  if (i < 0) throw CliException('pubspec.yaml has no `dependencies:` section.');
  lines.insertAll(i + 1, [
    '  # Added by flutter_ota: the patch module loader of the OTA toolchain. Keep it.',
    '  $loaderPackageName:',
    '    path: $loaderPackageRelDir',
  ]);
  final out = lines.join('\n');
  final check = loadYaml(out) as YamlMap;
  if ((check['dependencies'] as YamlMap?)?.containsKey(loaderPackageName) != true) {
    throw CliException('Could not add $loaderPackageName to pubspec.yaml automatically; add it by hand.');
  }
  f.writeAsStringSync(out);
  return true;
}
