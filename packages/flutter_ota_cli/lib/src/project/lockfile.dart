import 'dart:io';

import 'package:yaml/yaml.dart';

import '../errors.dart';
import '../toolchain/index.dart';

const lockFileName = 'flutter_ota.lock';

/// `flutter_ota.lock`: the exact toolchain a project builds with. Written only by the CLI
/// (`toolchain install` in a project without a lock, or `upgrade` after confirmation).
class Lockfile {
  Lockfile({
    required this.toolchain,
    required this.toolchainId,
    required this.flutter,
    required this.dart,
    required this.engine,
    required this.dartRevision,
  });

  factory Lockfile.fromEntry(ToolchainEntry e) => Lockfile(
    toolchain: e.id,
    toolchainId: e.toolchainId,
    flutter: e.flutter,
    dart: e.dart,
    engine: e.engine,
    dartRevision: e.dartRevision,
  );

  static const format = 1;

  final String toolchain;
  final String toolchainId;
  final String flutter;
  final String dart;
  final String engine;
  final String dartRevision;

  static Lockfile? readIn(String projectDir) {
    final f = File('$projectDir/$lockFileName');
    if (!f.existsSync()) return null;
    return parse(f.readAsStringSync(), f.path);
  }

  static Lockfile parse(String text, String where) {
    final Object? y;
    try {
      y = loadYaml(text);
    } on YamlException catch (e) {
      throw CliException('$where is not valid YAML: ${e.message}');
    }
    if (y is! YamlMap || y['format'] != format) {
      throw CliException('$where has an unsupported format. It is generated by flutter_ota; do not edit it by hand.');
    }
    final map = y;
    String s(String k) {
      final v = map[k];
      if (v is! String || v.isEmpty) throw CliException('$where: "$k" is missing. Do not edit this file by hand.');
      return v;
    }

    return Lockfile(
      toolchain: s('toolchain'),
      toolchainId: s('toolchain_id'),
      flutter: s('flutter'),
      dart: s('dart'),
      engine: s('engine'),
      dartRevision: s('dart_revision'),
    );
  }

  /// True when [e] is exactly the toolchain this lock pins.
  bool matches(ToolchainEntry e) =>
      e.id == toolchain &&
      e.toolchainId == toolchainId &&
      e.flutter == flutter &&
      e.dart == dart &&
      e.engine == engine &&
      e.dartRevision == dartRevision;

  String serialize() =>
      '# Generated by flutter_ota. Do not edit by hand; use `flutter_ota upgrade`.\n'
      'format: $format\n'
      'toolchain: "$toolchain"\n'
      'toolchain_id: "$toolchainId"\n'
      'flutter: "$flutter"\n'
      'dart: "$dart"\n'
      'engine: "$engine"\n'
      'dart_revision: "$dartRevision"\n';

  /// Writes atomically (temp file + rename).
  void writeTo(String projectDir) {
    final tmp = File('$projectDir/$lockFileName.tmp');
    tmp.writeAsStringSync(serialize(), flush: true);
    tmp.renameSync('$projectDir/$lockFileName');
  }
}
